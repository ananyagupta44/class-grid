import ExcelJS from "exceljs";
import PDFDocument from "pdfkit";
import { stamp, clean, show } from "./auditFile.js";

const HEAD = ["#", "Date & time", "User", "Email", "Role", "Action", "Module", "Record", "What changed"];
const tz = () => process.env.AUDIT_TIMEZONE || "Asia/Kolkata";

// ---------- what goes in each cell ----------
export function detailsOf(r) {
  if (r.changes?.length) {
    const lines = r.changes.slice(0, 8).map((c) => `${clean(c.field, 40)}: ${show(c.from)} -> ${show(c.to)}`);
    if (r.changes.length > 8) lines.push(`(+${r.changes.length - 8} more fields)`);
    return lines.join("\n");
  }
  if (r.action === "create") return "New record created";
  if (r.action === "delete") return "Record deleted";
  if (r.meta && typeof r.meta === "object") {
    return clean(
      Object.entries(r.meta)
        .map(([k, v]) => `${k}: ${typeof v === "object" ? JSON.stringify(v) : v}`)
        .join(", "),
      300,
    );
  }
  if (typeof r.meta === "string") return clean(r.meta, 300);
  return clean(r.summary || "", 300);
}

function whoOf(r) {
  const a = r.actor || {};
  if (a.system) return { name: "system", email: "", role: "" };
  if (!a.id && !a.name && !a.email) return { name: "anonymous", email: "", role: "" };
  return { name: a.name || "unknown", email: a.email || "", role: a.role || "" };
}

const tableRows = (rows) =>
  rows.map((r, i) => {
    const w = whoOf(r);
    return [i + 1, stamp(new Date(r.createdAt)), w.name, w.email, w.role, String(r.action).toUpperCase(), r.entity, r.label || "", detailsOf(r)];
  });

function stats(rows) {
  const byAction = new Map();
  const byUser = new Map();

  for (const r of rows) {
    const action = String(r.action).toUpperCase();
    byAction.set(action, (byAction.get(action) || 0) + 1);

    const w = whoOf(r);
    const key = `${w.name}|${w.email}`;
    byUser.set(key, { ...w, count: (byUser.get(key)?.count || 0) + 1 });
  }

  return {
    byAction: [...byAction].sort((a, b) => b[1] - a[1]),
    byUser: [...byUser.values()].sort((a, b) => b.count - a.count),
  };
}

const dayText = (d) => (d ? stamp(d).slice(0, 10) : "-");

function infoLines(meta) {
  const by = meta.generatedBy || {};
  return [
    ["Generated on", `${stamp(meta.generatedAt)} (${tz()})`],
    ["Generated by", `${by.name || "unknown"} <${by.email || "no email"}>`],
    ["Period", meta.from || meta.to ? `${dayText(meta.from)}  to  ${dayText(meta.to)}` : "all time"],
    ["Filters", meta.filters || "none"],
    ["Total entries", meta.capped ? `${meta.total} (newest ${meta.total} shown, narrow the dates to see older ones)` : String(meta.total)],
  ];
}

// =====================================================================
//  EXCEL
// =====================================================================
export async function writeXlsx(rows, meta, res) {
  const wb = new ExcelJS.Workbook();
  wb.creator = "ClassGrid";
  wb.created = meta.generatedAt;

  const thin = { style: "thin", color: { argb: "FFD9CFB8" } };
  const dark = { type: "pattern", pattern: "solid", fgColor: { argb: "FF1C2B26" } };

  // ----- sheet 1: summary -----
  const s = wb.addWorksheet("Summary");
  s.columns = [{ width: 22 }, { width: 44 }, { width: 14 }];
  s.mergeCells("A1:C1");
  s.getCell("A1").value = meta.title;
  s.getCell("A1").font = { bold: true, size: 16, color: { argb: "FF1C2B26" } };

  let n = 3;
  for (const [k, v] of infoLines(meta)) {
    s.getRow(n).getCell(1).value = k;
    s.getRow(n).getCell(1).font = { bold: true };
    s.getRow(n).getCell(2).value = v;
    s.mergeCells(n, 2, n, 3);
    n++;
  }

  const { byAction, byUser } = stats(rows);

  const block = (title, head, data) => {
    n++;
    s.getRow(n).getCell(1).value = title;
    s.getRow(n).getCell(1).font = { bold: true, size: 12 };
    n++;
    head.forEach((h, i) => {
      const c = s.getRow(n).getCell(i + 1);
      c.value = h;
      c.font = { bold: true, color: { argb: "FFFFFFFF" } };
      c.fill = dark;
    });
    for (const row of data) {
      n++;
      row.forEach((v, i) => {
        const c = s.getRow(n).getCell(i + 1);
        c.value = v;
        c.border = { top: thin, bottom: thin, left: thin, right: thin };
      });
    }
    n++;
  };

  block("Entries by action", ["Action", "", "Entries"], byAction.map(([a, c]) => [a, "", c]));
  block("Entries by user", ["User", "Email", "Entries"], byUser.slice(0, 25).map((u) => [u.name, u.email, u.count]));

  // ----- sheet 2: every entry -----
  const ws = wb.addWorksheet("Audit log", {
    views: [{ state: "frozen", ySplit: 1 }],
    pageSetup: { orientation: "landscape", fitToPage: true, fitToWidth: 1, fitToHeight: 0 },
  });
  ws.columns = HEAD.map((h, i) => ({ header: h, width: [5, 20, 20, 28, 15, 11, 16, 24, 70][i] }));

  for (const r of tableRows(rows)) ws.addRow(r);

  ws.eachRow((row, num) => {
    row.alignment = { vertical: "top", wrapText: true };
    if (num > 1) row.eachCell((c) => (c.border = { top: thin, bottom: thin, left: thin, right: thin }));
  });

  const head = ws.getRow(1);
  head.height = 20;
  head.alignment = { vertical: "middle" };
  head.eachCell((c) => {
    c.font = { bold: true, color: { argb: "FFFFFFFF" } };
    c.fill = dark;
  });
  ws.autoFilter = { from: "A1", to: "I1" };

  await wb.xlsx.write(res);
  res.end();
}

// =====================================================================
//  PDF  (landscape A4, header repeated on every page, "Page x of y")
// =====================================================================
export function writePdf(rows, meta, res) {
  const M = { top: 30, bottom: 38, left: 30, right: 30 };
  const doc = new PDFDocument({ size: "A4", layout: "landscape", margins: M, bufferPages: true, info: { Title: meta.title, Author: "ClassGrid" } });
  doc.pipe(res);

  const W = [26, 82, 78, 120, 62, 54, 62, 88, 210]; // adds up to the 782pt between the margins
  const TOTAL = W.reduce((a, b) => a + b, 0);
  const PAD = 3;
  const bottomY = () => doc.page.height - M.bottom;

  // title block
  doc.font("Helvetica-Bold").fontSize(17).fillColor("#1c2b26").text(meta.title, M.left, M.top);
  doc.moveDown(0.3);
  for (const [k, v] of infoLines(meta)) {
    doc.font("Helvetica-Bold").fontSize(8.5).fillColor("#444").text(`${k}: `, { continued: true });
    doc.font("Helvetica").fillColor("#111").text(v);
  }
  const { byAction } = stats(rows);
  if (byAction.length) {
    doc.moveDown(0.2);
    doc.font("Helvetica-Bold").fontSize(8.5).fillColor("#444").text("By action: ", { continued: true });
    doc.font("Helvetica").fillColor("#111").text(byAction.map(([a, c]) => `${a} ${c}`).join("   |   "));
  }

  let y = doc.y + 10;

  const header = () => {
    doc.save();
    doc.rect(M.left, y, TOTAL, 16).fill("#1c2b26");
    doc.fillColor("#ffffff").font("Helvetica-Bold").fontSize(7.5);
    let x = M.left;
    HEAD.forEach((h, i) => {
      doc.text(h, x + PAD, y + 4.5, { width: W[i] - 2 * PAD, lineBreak: false, ellipsis: true });
      x += W[i];
    });
    doc.restore();
    y += 16;
  };

  if (!rows.length) {
    doc.font("Helvetica").fontSize(10).fillColor("#666").text("No entries for the selected filters.", M.left, y);
  } else {
    header();
    doc.font("Helvetica").fontSize(7.5);

    tableRows(rows).forEach((cells, idx) => {
      const texts = cells.map(String);
      const h = Math.max(...texts.map((t, i) => doc.heightOfString(t, { width: W[i] - 2 * PAD }))) + 2 * PAD;

      if (y + h > bottomY()) {
        doc.addPage();
        y = M.top;
        header();
        doc.font("Helvetica").fontSize(7.5);
      }

      if (idx % 2 === 1) doc.save().rect(M.left, y, TOTAL, h).fill("#f6f1e3").restore();
      doc.save().moveTo(M.left, y + h).lineTo(M.left + TOTAL, y + h).lineWidth(0.4).strokeColor("#d9cfb8").stroke().restore();

      doc.fillColor("#111");
      let x = M.left;
      texts.forEach((t, i) => {
        doc.text(t, x + PAD, y + PAD, { width: W[i] - 2 * PAD });
        x += W[i];
      });
      y += h;
    });
  }

  // footer on every page
  const range = doc.bufferedPageRange();
  for (let i = 0; i < range.count; i++) {
    doc.switchToPage(i);
    const keep = doc.page.margins.bottom;
    doc.page.margins.bottom = 0; // otherwise writing down here would add a blank page
    doc.font("Helvetica").fontSize(7).fillColor("#666").text(`${meta.title}   |   Page ${i + 1} of ${range.count}`, M.left, doc.page.height - 22, {
      width: TOTAL,
      align: "center",
      lineBreak: false,
    });
    doc.page.margins.bottom = keep;
  }

  doc.end();
}
