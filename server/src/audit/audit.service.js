import AuditLog from "../models/AuditLog.js";
import mongoose from "mongoose";
import { currentActor } from "./auditContext.js";
import { writeAuditLine } from "./auditFile.js";

const IGNORE_FIELDS = new Set(["_id", "__v", "createdAt", "updatedAt"]);
const SECRET_KEY = /pass(word)?|token|secret/i; // never written to the log
const LABEL_FIELDS = ["name", "title", "slug", "roomNo", "subjectId", "courseId", "facultyId", "identifier", "email"];
const MAX_VALUE_CHARS = 2000;
const MAX_SNAPSHOT_CHARS = 10000;

// ObjectId -> string, Date -> ISO string, Mongoose doc -> plain object
const plain = (v) => (v === undefined ? null : JSON.parse(JSON.stringify(v)));

const redact = (v) => {
  if (Array.isArray(v)) return v.map(redact);

  if (v && typeof v === "object") {
    return Object.fromEntries(
      Object.entries(v).map(([k, x]) => [
        k.replace(/^\$/, "_$").replace(/\./g, "_"), // Mongo does not allow keys like "$set" or "a.b"
        SECRET_KEY.test(k) ? "[redacted]" : redact(x),
      ]),
    );
  }

  return v;
};

const clip = (v, max) => {
  const s = JSON.stringify(v);

  return s && s.length > max ? `[too large to store: ${s.length} characters]` : v;
};

// a filter / update object as readable text, e.g. {"$set":{"status":"rejected"}} (passwords removed)
export const asText = (v) => clip(JSON.stringify(redact(plain(v))), MAX_VALUE_CHARS);

// readable name of a record
export const labelOf = (doc) => {
  if (!doc) return undefined;

  const d = typeof doc.toObject === "function" ? doc.toObject() : doc;

  for (const f of LABEL_FIELDS) if (typeof d[f] === "string" && d[f]) return d[f];

  return undefined;
};

// field-by-field difference between two versions of a record
export function diffDocs(before, after) {
  const b = plain(before) || {};
  const a = plain(after) || {};
  const changes = [];

  for (const field of new Set([...Object.keys(b), ...Object.keys(a)])) {
    if (IGNORE_FIELDS.has(field)) continue;

    if (JSON.stringify(b[field] ?? null) === JSON.stringify(a[field] ?? null)) continue;

    const secret = SECRET_KEY.test(field);

    changes.push({
      field,
      from: secret ? "[redacted]" : clip(redact(b[field] ?? null), MAX_VALUE_CHARS),
      to: secret ? "[redacted]" : clip(redact(a[field] ?? null), MAX_VALUE_CHARS),
    });
  }

  return changes;
}

const VERB = {
  create: "created",
  update: "updated",
  delete: "deleted",
  "bulk-update": "bulk-updated",
  "bulk-delete": "bulk-deleted",
};

function summarize({ actor, action, entity, label, changes }) {
  const who = actor.name || actor.email || (actor.system ? "system" : "anonymous");

  let s = `${who} ${VERB[action] || action} ${entity}${label ? ` "${label}"` : ""}`;

  if (changes?.length) s += ` (${changes.map((c) => c.field).join(", ")})`;

  return s;
}

// If the login token only carries the user id, look up the name / email once (cached 10 minutes)
const profileCache = new Map();

async function withProfile(actor) {
  if (actor.system || !actor.id || (actor.name && actor.email)) return actor;

  const User = mongoose.models.User;
  if (!User) return actor;

  const key = String(actor.id);
  let hit = profileCache.get(key);

  if (!hit || Date.now() - hit.at > 10 * 60 * 1000) {
    const doc = await User.findById(key).select("name email role").lean().catch(() => null);
    hit = { at: Date.now(), doc };
    profileCache.set(key, hit);
  }

  return {
    ...actor,
    name: actor.name || hit.doc?.name,
    email: actor.email || hit.doc?.email,
    role: actor.role || hit.doc?.role,
  };
}

// the logged-in user with name / email filled in (used for "Generated by" on reports)
export const actorProfile = async () => withProfile(currentActor());

// Writes one audit entry to the database AND to the daily log file.
// NEVER throws: if logging fails, the real change has already been saved.
export async function logAudit({ action, entity, entityId, label, changes, snapshot, summary, meta }) {
  try {
    const actor = await withProfile(currentActor());

    const entry = {
      actor: {
        id: actor.id ? String(actor.id) : undefined,
        name: actor.name,
        email: actor.email,
        role: actor.role,
        system: actor.system || undefined,
      },
      action,
      entity,
      entityId: entityId === undefined ? undefined : String(entityId),
      label,
      changes,
      snapshot: snapshot === undefined ? undefined : clip(redact(plain(snapshot)), MAX_SNAPSHOT_CHARS),
      summary: summary || summarize({ actor, action, entity, label, changes }),
      request: { ip: actor.ip, method: actor.method, path: actor.path },
      meta: meta === undefined ? undefined : clip(redact(plain(meta)), MAX_VALUE_CHARS),
    };

    try {
      await AuditLog.create(entry);
    } catch (err) {
      console.error("AUDIT LOG ERROR (the change itself was saved):", err.message);
    }

    await writeAuditLine(entry); // the log file, even if the database write above failed
  } catch (err) {
    console.error("AUDIT LOG ERROR (the change itself was saved):", err.message);
  }
}
